import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { CONTRATO_RPC } from "../src/lib/rpc-contrato.ts";

/*
  Tabela oficial de cargos, fase 1 (20261104150000). O ensaio (begin…rollback,
  em 04/11/2026) conferiu: 91 cargos, todos da Saúde Indígena, código = código
  SIP, sintéticos 9994–9997 e 9999; os 21 casos de
  tests/fixtures/cargos/normalizacao.json sem diferença; FC_CARGO_DA_GRAFIA
  devolve 63 para "Enfermeiro" e para o apelido confirmado "Enfermeiro (a)",
  74 para "Médico 40h", nulo para "Médico" (sem carga horária), para apelido
  pendente, para outra área e para "Psicólogo"; recusas 23514 (grafia não
  normalizada, automático sem regra, confirmado sem data, SIP ≠ código),
  23505 (grafia e nome repetidos, SIP repetido) e 23503 (apelido de outra área);
  cargo sem SIP a partir de 100000; listar_cargos: administrador global vê
  todas as áreas, pessoa da Saúde Indígena só a dela, pessoa de fora nada;
  authenticated não lê as tabelas nem executa as funções de private (42501);
  sem sessão, 28000. Invariantes estáticas abaixo.
*/
const ler = (arquivo) => readFileSync(arquivo, "utf8").replace(/\r\n/g, "\n");
const NOME = "20261104150000_tabela_de_cargos.sql";
const MIGRATION = ler(`supabase/migrations/${NOME}`);
const ROLLBACK = ler(`supabase/rollback/${NOME}`);
const ENSAIO = ler(`supabase/ensaios/${NOME}`);
const TABELAS = ["TD_CARGO", "TD_CARGO_APELIDO"];

describe("tabela de cargos (migration)", () => {
  it("tabelas MAD com RLS, sem privilégio para ninguém e com COMMENT ON em tudo", () => {
    for (const tabela of TABELAS) {
      const inicio = MIGRATION.indexOf(`create table public."${tabela}" (`);
      expect(inicio).toBeGreaterThan(0);
      const ddl = MIGRATION.slice(inicio, MIGRATION.indexOf("\n);", inicio));
      expect(MIGRATION).toContain(`constraint "PK_${tabela}" primary key`);
      expect(MIGRATION).toContain(`comment on table public."${tabela}" is`);
      expect(MIGRATION).toContain(
        `alter table public."${tabela}" enable row level security;`,
      );
      expect(MIGRATION).toContain(
        `revoke all on public."${tabela}" from public, anon, authenticated, service_role;`,
      );
      expect(ROLLBACK).toContain(`drop table if exists public."${tabela}";`);
      for (const m of ddl.matchAll(/^ {2}"([A-Z_]+)" /gm)) {
        expect(m[1]).toMatch(/^(CO|NO|DS|DT|ST|TP|VL)_/);
        expect(MIGRATION).toContain(
          `comment on column public."${tabela}"."${m[1]}" is`,
        );
      }
      for (const m of ddl.matchAll(/constraint "([A-Z_]+)"/g)) {
        expect(MIGRATION).toContain(`comment on constraint "${m[1]}" on`);
      }
    }
    for (const m of MIGRATION.matchAll(/create (?:unique )?index "([A-Z_]+)"/g))
      expect(MIGRATION).toContain(`comment on index public."${m[1]}" is`);
  });

  it("código do cargo = código SIP; sem SIP a partir de 100000; apelido único por área", () => {
    expect(MIGRATION).toContain(
      `"CO_CARGO" integer generated by default as identity (start with 100000)`,
    );
    expect(MIGRATION).toContain(
      `("CO_CARGO_SIP" between 1 and 99999 and "CO_CARGO" = "CO_CARGO_SIP")`,
    );
    expect(MIGRATION).toContain(
      `constraint "UK_TDCARGOAPELIDO_AREA_GRAFIA" unique ("CO_AREA", "DS_GRAFIA_NORMALIZADA")`,
    );
    expect(MIGRATION).toContain(
      `foreign key ("CO_CARGO", "CO_AREA")\n    references public."TD_CARGO" ("CO_CARGO", "CO_AREA")`,
    );
    expect(MIGRATION).toContain(
      `check ("TP_ORIGEM" in ('AUTOMATICO', 'MANUAL'))`,
    );
    // A carga: 91 linhas, os 5 sintéticos.
    const carga = [...MIGRATION.matchAll(/^ {4}\((\d+), '.*', '([SN])'\)/gm)];
    expect(carga).toHaveLength(91);
    expect(carga.filter((m) => m[2] === "S").map((m) => Number(m[1]))).toEqual([
      9994, 9995, 9996, 9997, 9999,
    ]);
    // Nenhum apelido gravado pela migration (a carga é a correção, com autorização).
    expect(MIGRATION).not.toMatch(/insert into public\."TD_CARGO_APELIDO"/);
  });

  it("normalização imutável; leitura por RPC SECURITY DEFINER, search_path vazio, sem anon", () => {
    const funcoes = MIGRATION.split(/^create function /m).slice(1);
    expect(funcoes).toHaveLength(3);
    for (const funcao of funcoes)
      expect(funcao).toMatch(/\nset search_path to ''\n/);
    expect(funcoes[0]).toMatch(
      /^private\."FC_NORMALIZAR_GRAFIA_CARGO"\(p_texto text\)\nreturns text\nlanguage sql\nimmutable\n/,
    );
    for (const funcao of funcoes.slice(1))
      expect(funcao).toContain("security definer\nset search_path to ''");
    expect(MIGRATION).toContain(
      `revoke all on function public.listar_cargos(text) from public, anon;`,
    );
    expect(MIGRATION).toContain(
      `grant execute on function public.listar_cargos(text) to authenticated;`,
    );
    expect(MIGRATION.match(/^grant .*$/gm)).toHaveLength(1);
    for (const privada of [
      `private."FC_NORMALIZAR_GRAFIA_CARGO"(text)`,
      `private."FC_CARGO_DA_GRAFIA"(text, text)`,
    ]) {
      expect(MIGRATION).toContain(
        `revoke all on function ${privada} from public, anon, authenticated, service_role;`,
      );
      expect(ROLLBACK).toContain(`drop function if exists ${privada};`);
    }
    expect(ROLLBACK).toContain(
      "drop function if exists public.listar_cargos(text);",
    );
    // Administrador global passa sempre; os demais, pelas áreas que veem.
    expect(
      MIGRATION.match(
        /\(private\.is_master\(\) or private\."FC_PODE_AREA"\([ac]\."CO_AREA"\)\)/g,
      ),
    ).toHaveLength(2);
    expect(MIGRATION).toContain("using errcode = '28000'");
    // Só apelido confirmado vale.
    expect(MIGRATION).toContain(`and a."ST_CONFIRMADO" = 'S'`);
  });

  it("fase 1: não mexe nas colunas existentes, nas funções nem no contrato do front", () => {
    expect(MIGRATION).not.toMatch(/alter table public\."TB_/);
    expect(MIGRATION).not.toMatch(/create or replace function/);
    expect(MIGRATION).not.toMatch(/drop /);
    expect(CONTRATO_RPC.listar_cargos).toBeUndefined();
  });

  it("ensaio com o corpo da migration, sempre desfeito e sem carga em lote", () => {
    const corpo = MIGRATION.slice(
      MIGRATION.indexOf("\nbegin;\n") + 8,
      MIGRATION.indexOf("\nnotify pgrst"),
    ).trim();
    expect(ENSAIO).toContain(corpo);
    expect(ENSAIO).not.toMatch(/^\s*commit\s*;/im);
    expect(ENSAIO.trim().endsWith("rollback;")).toBe(true);
    expect(ENSAIO).not.toMatch(/generate_series/);
    for (const tipo of ["admin_global", "da_si", "fora_da_si"])
      expect(ENSAIO).toContain(`'${tipo}'`);
  });
});
