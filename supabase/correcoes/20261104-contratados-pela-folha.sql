create function pg_temp.md5_114() returns text language sql as $f$
  select md5(coalesce(string_agg(c.id::text || '=' || coalesce(c.status, '') || '|' || coalesce(c.matricula, ''), ',' order by c.id), ''))
    from public."TB_CANDIDATO_APROVADO" c join public."TB_LISTA_APROVADO" l on l.id = c.lista_id
   where l.edital_id = 'bcecfb08-88ef-4e06-8401-bcad6bf88fd0';
$f$;
create temporary table tmp_md5_114 on commit drop as select pg_temp.md5_114() as antes;

do $$
declare v_n integer; v_esperado integer := 787;
begin
  if (select count(*) from tmp_contratados_folha) <> v_esperado then
    raise exception 'A lista da correção não tem % linhas: nada foi gravado.', v_esperado;
  end if;
  -- Cada linha ainda como na conferência: lista vigente, não removida, fora do 114, mesma situação e matrícula.
  select count(*) into v_n
    from tmp_contratados_folha t
    join public."TB_CANDIDATO_APROVADO" c on c.id = t.id
    join public."TB_LISTA_APROVADO" l on l.id = c.lista_id
   where l.vigente and c.removido_em is null
     and l.edital_id is distinct from 'bcecfb08-88ef-4e06-8401-bcad6bf88fd0'
     and c.status is not distinct from t.status_antes
     and coalesce(nullif(btrim(c.matricula), ''), '') = coalesce(t.matricula_antes, '');
  if v_n <> v_esperado then
    raise exception '% de % linhas ainda estão como na conferência: nada foi gravado.', v_n, v_esperado;
  end if;
  -- Parte 2 só em edital encerrado: Concluído/Cancelado, lista inativa ou validade vencida.
  if exists (select 1 from tmp_contratados_folha t
               join public."TB_CANDIDATO_APROVADO" c on c.id = t.id
               join public."TB_LISTA_APROVADO" l on l.id = c.lista_id
               join public."TB_MONITORAMENTO_INDIGENA" m on m.id::text = l.edital_id
              where t.parte = 2
                and not (m.status in ('Concluído', 'Cancelado') or l.ativo is false
                         or private."FC_VENCIMENTO_DO_EDITAL"(m.data_fim::date, m."NU_ANOS_VALIDADE", m."NU_MESES_VALIDADE", m."ST_PRORROGADO")
                            < (now() at time zone 'America/Sao_Paulo')::date)) then
