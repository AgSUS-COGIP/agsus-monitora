-- 6. Leitura para a tela (fase 2) ----------------------------------------------------------------
create function public.listar_cargos(p_area text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path to ''
as $function$
begin
  if (select auth.uid()) is null then
    raise exception 'Sessão não localizada.' using errcode = '28000';
  end if;

  return jsonb_build_object(
    'cargos', coalesce((
      select jsonb_agg(jsonb_build_object(
               'codigo', c."CO_CARGO",
               'codigo_sip', c."CO_CARGO_SIP",
               'nome', c."NO_CARGO",
               'area', c."CO_AREA",
               'sintetico', c."ST_SINTETICO" = 'S',
               'ativo', c."ST_REGISTRO_ATIVO" = 'S',
               'apelidos', (select count(*) from public."TD_CARGO_APELIDO" a
                             where a."CO_CARGO" = c."CO_CARGO" and a."ST_REGISTRO_ATIVO" = 'S'
                               and a."ST_CONFIRMADO" = 'S'))
             order by c."CO_AREA", c."NO_CARGO")
        from public."TD_CARGO" c
       where (p_area is null or c."CO_AREA" = p_area)
         and (private.is_master() or private."FC_PODE_AREA"(c."CO_AREA"))), '[]'::jsonb),
    'apelidos_pendentes', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', a."CO_CARGO_APELIDO",
               'area', a."CO_AREA",
               'grafia', a."DS_GRAFIA_NORMALIZADA",
               'codigo', a."CO_CARGO",
               'cargo', c."NO_CARGO",
               'origem', a."TP_ORIGEM",
               'regra', a."TP_REGRA",
               'confianca', a."VL_CONFIANCA",
               'criado_em', a."DT_CRIACAO")
             order by a."CO_AREA", a."VL_CONFIANCA" desc nulls last, a."DS_GRAFIA_NORMALIZADA")
        from public."TD_CARGO_APELIDO" a
        join public."TD_CARGO" c on c."CO_CARGO" = a."CO_CARGO"
       where a."ST_CONFIRMADO" = 'N' and a."ST_REGISTRO_ATIVO" = 'S'
         and (p_area is null or a."CO_AREA" = p_area)
         and (private.is_master() or private."FC_PODE_AREA"(a."CO_AREA"))), '[]'::jsonb));
end;
$function$;
